// Every page that states a finalist/IBO total must match data/results.csv, including the
// invisible ones in <meta> tags.
function checkResultClaims(totals) {
  // Anchored deliberately tightly: a loose "(\\d+) ... finalist" also matches a YEAR
  // ("2019 USABO Finalist"), a rank ("Top 20 National Finalist") and the size of the
  // national field ("only 20 finalists") — correct sentences that are not our total. An
  // aggregate claim always puts the competition name immediately after the count, and
  // (?<!\d) stops \d{1,3} matching "019" inside "2019".
  const FINALISTS = /(?<!\d)(\d{1,3})\s+(?:USABO|USA Biology Olympiad)[^.]{0,48}?[Ff]inalist/g;
  // Allows text between the count and "Team USA" ("12 of which went on to represent Team
  // USA" — the caption this build writes) but forbids a digit in between, so
  // "52 ... Finalist places, 12 of which ... Team USA" matches only the 12.
  const TEAM_USA = /(?<!\d)(\d{1,3})\s+[^.<0-9]{0,70}?Team USA/g;
  const bad = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (SKIP_DIR.test(e.name)) continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) { walk(full); continue; }
      if (!e.name.endsWith(".html")) continue;
      const raw = fs.readFileSync(full, "utf8");
      const rel = path.relative(ROOT, full);
      // Only HAND-WRITTEN copy can drift. Regions between BUILD markers are derived from
      // the CSV, and the chart's own caption cites the national field size ("20 National
      // Finalists each year"), which is not our total — so they are blanked before scanning.
      const txt = raw.replace(/<!--\s*BUILD:[\w-]+\s*-->[\s\S]*?<!--\s*\/BUILD:[\w-]+\s*-->/g,
        (m) => m.replace(/[^\n]/g, " "));
      const line = (i) => txt.slice(0, i).split("\n").length;
      for (const m of txt.matchAll(FINALISTS)) {
        if (Number(m[1]) !== totals.finalists) {
          bad.push(`${rel}:${line(m.index)}  claims ${m[1]} finalists, data/results.csv says ${totals.finalists}`);
        }
      }
      for (const m of txt.matchAll(TEAM_USA)) {
        if (Number(m[1]) !== totals.ibo) {
          bad.push(`${rel}:${line(m.index)}  claims ${m[1]} Team USA, data/results.csv says ${totals.ibo}`);
        }
      }
    }
  };
  walk(ROOT);
  if (bad.length) {
    throw new Error("results claim guard failed:\n  - " + bad.join("\n  - ") +
      "\n\nEvery count comes from data/results.csv. Update the CSV, not the copy.");
  }
  console.log(`Results claim guard OK — every stated total matches data/results.csv (${totals.finalists}/${totals.ibo})`);
}

// --- Sitemap ------------------------------------------------------------
// Regenerate sitemap.xml (+ image sitemap) so search/AI crawlers can discover every page
// and every gallery image. Output is fully deterministic — no build-time or filesystem
// timestamps anywhere — so two clones of one commit produce byte-identical sitemaps and
// the file changes only when the page list, the photos, or a page's last COMMIT date does.
const SITE = "https://baology.org";

// --- robots meta --------------------------------------------------------
// A page whose own head says `<meta name="robots" content="noindex">` must not also be
// submitted in sitemap.xml: the two contradict each other and the page wins, so the entry
// is at best noise.
//
// Read from the page itself rather than a hardcoded exclusion list, so noindexing the next
// page is one tag edit and the sitemap follows with nobody in the loop. Scoped to <head>,
// the only place a crawler honours the tag, and with HTML comments stripped first so a
// commented-out tag cannot silently delete a live URL. `none` counts: the spec defines it
// as shorthand for "noindex, nofollow".
const META_TAG = /<meta\b(?:"[^"]*"|'[^']*'|[^<>])*>/gi;

function attrValue(tag, name) {
  // (?<![-\w]) so `data-name=` / `itemprop-name=` is not read as `name=`.
  const m = new RegExp(`(?<![-\\w])${name}\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([^\\s"'=<>\`]+))`, "i").exec(tag);
  if (!m) return null;
  return m[1] != null ? m[1] : m[2] != null ? m[2] : m[3];
}

function htmlIsNoindex(html) {
  const head = /<head\b[^<>]*>([\s\S]*?)<\/head>/i.exec(html);
  const scope = (head ? head[1] : html).replace(/<!--[\s\S]*?-->/g, "");
  META_TAG.lastIndex = 0;
  for (const m of scope.matchAll(META_TAG)) {
    if ((attrValue(m[0], "name") || "").trim().toLowerCase() !== "robots") continue;
    const directives = (attrValue(m[0], "content") || "")
      .toLowerCase().split(",").map((d) => d.trim());
    if (directives.includes("noindex") || directives.includes("none")) return true;
  }
  return false;
}

// This reader failing is SILENT — a regex that stops matching quietly puts noindexed URLs
// back into the sitemap, and nobody reads sitemap.xml — so its cases are asserted on every
// build rather than described in a comment.
const NOINDEX_PROBE = [
  [`<head><meta name="robots" content="noindex"></head>`, true],
  [`<head><meta content="noindex" name="robots"></head>`, true],   // attribute order
  [`<head><meta name=robots content=noindex></head>`, true],       // unquoted
  [`<head><meta name='robots' content='NOINDEX, follow'></head>`, true],
  [`<head><meta name="ROBOTS" content="none"></head>`, true],      // spec shorthand
  [`<head><meta name="robots" content="index, follow"></head>`, false],
  [`<head><meta name="robots" content="max-image-preview:large"></head>`, false],
  // "noindex" appearing as prose in some OTHER meta must not exclude the page:
  [`<head><meta name="description" content="what noindex, none mean"></head>`, false],
  // a commented-out tag is not a live tag:
  [`<head><!-- <meta name="robots" content="noindex"> --></head>`, false],
  // ...and neither is one quoted in the body:
  [`<head><title>x</title></head><body><pre>&lt;meta name="robots" content="noindex"&gt;</pre></body>`, false],
  [`<head><meta name="description" content="a > b"><meta name="robots" content="noindex"></head>`, true],
  [`<html><head></head><body></body></html>`, false],
  // a look-alike attribute name is not the attribute:
  [`<head><meta data-name="robots" content="noindex"></head>`, false],
];
let noindexProbed = false;
function probeNoindex() {
  if (noindexProbed) return;
  noindexProbed = true;
  const bad = NOINDEX_PROBE
    .filter(([html, want]) => htmlIsNoindex(html) !== want)
    .map(([html, want]) => `  want ${want}: ${html}`);
  if (bad.length) {
    throw new Error(
      "robots-meta reader SELF-TEST failed — sitemap.xml would be built from a\n" +
      "wrong answer about which pages are noindexed:\n" + bad.join("\n")
    );
  }
}

// File-level wrapper: unreadable means "cannot prove it is noindexed", so the URL
// stays — but say so, because a sitemap entry whose file is not on disk is a 404
// handed to a crawler and that is worth hearing about too.
function pageIsNoindex(file) {
  probeNoindex();
  try {
    return htmlIsNoindex(fs.readFileSync(path.join(ROOT, file), "utf8"));
  } catch (e) {
    console.warn(`  ! sitemap: could not read ${file} to check its robots meta: ${e.message}`);
    return false;
  }
}

// --- lastmod ------------------------------------------------------------
// The date a URL last changed, read from GIT, not from the filesystem. mtime is a property
// of the checkout, not of the content, so two clones of one commit would disagree and any
// checkout would mint dates it did not earn. A wrong lastmod is worse than none: crawlers
// that catch a sitemap lying about it stop trusting the field. `%cs` (committer date) is
// stored in the commit object, so every clone of a commit agrees.
//
// One `git log` for the whole page list. Files with no commit yet, and every file when git
// is unavailable (a tarball export), get NO <lastmod> — omitting it is the honest answer.
//
// Known and accepted: the date lags by one commit for a page whose own edit is the change
// being committed, because the pre-commit hook builds before that commit exists. It
// self-corrects on the next build.
function gitLastMod(files) {
  const dates = new Map();
  if (!files.length) return dates;
  const log = spawnSync("git",
    ["log", "--format=%x00%cs", "--name-only", "--", ...files],
    { cwd: ROOT, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  if (log.error || log.status !== 0) {
    console.warn("  ! sitemap: git unavailable — every <lastmod> omitted.");
    return dates;
  }
  const want = new Set(files);
  // Records are newest-first and NUL-delimited: "<date>\n\n<path>\n<path>…".
  // First record naming a path wins; later (older) records cannot overwrite it.
  for (const rec of log.stdout.split("\0")) {
    const lines = rec.split("\n").map((l) => l.trim()).filter(Boolean);
    const date = lines.shift();
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date || "")) continue;
    for (const f of lines) if (want.has(f) && !dates.has(f)) dates.set(f, date);
  }
  return dates;
}

function buildSitemap(photos, blogs) {
  // Hand-maintained list of top-level pages (excludes the header.html fragment
  // and unpublished sample blog files). 404.html is excluded by its own
  // `<meta name="robots" content="noindex">`, like every other noindexed page —
  // see the filter below.
  const pages = [
    { url: "/", file: "index.html" },
    { url: "/about.html", file: "about.html" },
    { url: "/about/faq.html", file: "about/faq.html" },
    { url: "/about/syllabus.html", file: "about/syllabus.html" },
    { url: "/signup.html", file: "signup.html" },
    { url: "/demo/", file: "demo/index.html" },
    { url: "/explore.html", file: "explore.html" },
    { url: "/explore/testimonials.html", file: "explore/testimonials.html" },
    { url: "/blog-main.html", file: "blog-main.html" },
  ];
  // Published blog posts — only those linked from blogs.json. De-duplicated
  // and sorted so the order is stable across builds.
  const blogPages = [...new Set(blogs.map(b => "/" + String(b.link).replace(/^\/+/, "")))]
    .sort()
    .map((url) => ({ url, file: url.slice(1) }));

  // The gallery page carries an <image:image> entry per photo. Sorted by src
  // so adding/editing a caption doesn't reorder the whole block.
  const imageEntries = [...photos]
    .sort((a, b) => (a.src < b.src ? -1 : a.src > b.src ? 1 : 0))
    .map(p => {
      const title = (p.location || "").trim();
      const caption = (p.description || p.alt || "").trim();
      return [
        `    <image:image>`,
        `      <image:loc>${escapeHtml(SITE + p.src)}</image:loc>`,
        title ? `      <image:title>${escapeHtml(title)}</image:title>` : null,
        caption ? `      <image:caption>${escapeHtml(caption)}</image:caption>` : null,
        `    </image:image>`,
      ].filter(Boolean).join("\n");
    })
    .join("\n");

  // The gallery goes through the same filter as everything else — one list, one
  // rule — so noindexing it would drop its image entries with it rather than
  // leaving them behind in a hand-written special case.
  const gallery = { url: "/explore/gallery.html", file: "explore/gallery.html", images: imageEntries };

  const skipped = [];
  const indexed = [...pages, ...blogPages, gallery].filter((e) => {
    if (!pageIsNoindex(e.file)) return true;
    skipped.push(e.url);
    return false;
  });
  const lastmods = gitLastMod(indexed.map((e) => e.file));
  const urls = indexed
    .map(({ url, file, images }) => {
      const lastmod = lastmods.get(file);
      const lastmodTag = lastmod ? `\n    <lastmod>${lastmod}</lastmod>` : "";
      const imageBlock = images ? `\n${images}` : "";
      return `  <url>\n    <loc>${escapeHtml(SITE + url)}</loc>${lastmodTag}${imageBlock}\n  </url>`;
    });

  const xml = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"`,
    `        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">`,
    urls.join("\n"),
    `</urlset>`,
    ``,
  ].join("\n");
  return { xml, skipped };
}

// --- Marker injection ---------------------------------------------------
function injectBetweenMarkers(html, name, content) {
  const open = `<!-- BUILD:${name} -->`;
  const close = `<!-- /BUILD:${name} -->`;
  const re = new RegExp(`${open.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\$&")}[\\s\\S]*?${close.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\$&")}`, "g");
  if (!re.test(html)) {
    throw new Error(`Marker pair not found: ${name}`);
  }
  re.lastIndex = 0;
  return html.replace(re, `${open}\n${content}\n        ${close}`);
}

// --- Static nav sync (header.html is the single source) -----------------
// Every page carries its nav as static, crawlable HTML; this keeps them all in
// sync with header.html on each build. Replaces either an inlined
// <header class="navigation…">…</header> block or a <div id="header"></div>
// placeholder, so a new page only needs one of those where the nav belongs.
function syncNav() {
  const nav = fs.readFileSync(path.join(ROOT, "header.html"), "utf8").trim();
  const navRe = /<header class="navigation[\s\S]*?<\/header>/;
  // header.html must be EXACTLY one <header> element. Anything outside it — a leading comment, say —
  // gets copied into every page but is not matched by navRe on the next build, so each build appends
  // another copy and never removes the old one. That happened: a 919-byte comment reached 5 copies on
  // each of 20 pages before it was caught. Put such comments INSIDE <header>.
  if (!/^<header class="navigation[\s\S]*<\/header>$/.test(nav)) {
    throw new Error(
      "header.html has content outside its <header> element.\n" +
      "syncNav() copies the whole file in but only matches <header>...</header> on the way back out,\n" +
      "so anything outside it accumulates one more copy per build. Move it inside <header>."
    );
  }
  const placeholderRe = /<div id="header">\s*<\/div>/;
  const skipFiles = new Set(["header.html", "footer.html"]);
  let count = 0;
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith(".")) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIR.test(entry.name)) walk(full);
        continue;
      }
      if (!entry.name.endsWith(".html")) continue;
      if (skipFiles.has(path.relative(ROOT, full))) continue;
      const html = fs.readFileSync(full, "utf8");
      let out = html;
      if (navRe.test(out)) out = out.replace(navRe, nav);
      else if (placeholderRe.test(out)) out = out.replace(placeholderRe, nav);
      else continue;                 // no nav here — not a page this build owns
      claim(full);
      if (out !== html) { fs.writeFileSync(full, out); count++; }
    }
  })(ROOT);
  console.log(`Synced static nav into ${count} page(s) from header.html`);
}

// --- Build ---------------------------------------------------------------
// Overlay dims (--scrim-lightbox / --scrim-modal) override vendor CSS by load order alone.
// A plugin upgrade can reintroduce a hardcoded dim or move it to a new, more specific
// selector, and nothing would notice until someone opened the lightbox on a phone — so
// fail the build instead. The fingerprint hashes the SET of vendor rules that paint a dim,
// not each rule individually, which is what catches a brand-new selector being added.
const SCRIM_VENDOR_FINGERPRINT = "e5732dbdb087";

function checkScrims() {
  const crypto = require("crypto");
  const vendorFiles = [
    "plugins/glightbox/glightbox.min.css",
    "plugins/bootstrap/bootstrap.min.css",
  ];
  // Matches innermost rules only, so @media-nested rules are captured too.
  // Note: a regex that consumes its leading delimiter skips every other rule in
  // a minified file. This form does not.
  const RULE = /([^{}]+)\{([^{}]*)\}/g;
  const found = [];
  for (const rel of vendorFiles) {
    const css = fs.readFileSync(path.join(ROOT, rel), "utf8");
    let m;
    RULE.lastIndex = 0;
    while ((m = RULE.exec(css)) !== null) {
      const sel = m[1].trim(), body = m[2].trim();
      if (!/goverlay|modal-backdrop/.test(sel)) continue;
      if (!/(^|;)\s*(background|background-color|opacity)\s*:/.test(";" + body)) continue;
      found.push(`${rel}|${sel}{${body}}`);
    }
  }
  const fp = crypto.createHash("sha256")
    .update(found.sort().join("\n")).digest("hex").slice(0, 12);

  const errors = [];
  if (fp !== SCRIM_VENDOR_FINGERPRINT) {
    errors.push(
      `vendor scrim rules changed (pinned ${SCRIM_VENDOR_FINGERPRINT}, found ${fp}).\n` +
      `  ${found.length} vendor rule(s) currently paint a dim:\n` +
      found.map((f) => "    " + f).join("\n")
    );
  }

  const site = fs.readFileSync(path.join(ROOT, "css/style.css"), "utf8");
  const required = [
    [".goverlay", "--scrim-lightbox"],
    [".glightbox-mobile .goverlay", "--scrim-lightbox"],
    [".modal-backdrop", "--scrim-modal"],
    [".modal-backdrop.show", null],
  ];
  for (const [sel, token] of required) {
    const esc = sel.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    if (!new RegExp(`(^|,|\\})\\s*${esc}\\s*(,|\\{)`, "m").test(site)) {
      errors.push(`css/style.css has no override for \`${sel}\``);
    }
    if (token && !site.includes(`var(${token}`)) {
      errors.push(`css/style.css never references var(${token})`);
    }
  }
  for (const t of ["--scrim-lightbox", "--scrim-modal"]) {
    if (!new RegExp(`^\\s*${t}\\s*:`, "m").test(site)) {
      errors.push(`token ${t} is not defined in :root`);
    }
  }
  if (!/\.modal-backdrop\.show\s*\{[^}]*opacity\s*:\s*1\b/.test(site)) {
    errors.push("`.modal-backdrop.show { opacity: 1 }` is missing — Bootstrap's .5 would multiply --scrim-modal's alpha");
  }

  if (errors.length) {
    throw new Error(
      "scrim guard failed:\n  - " + errors.join("\n  - ") +
      "\n\nThe overlay dims are tokenized in css/style.css (:root --scrim-*).\n" +
      "Re-audit the vendor rules listed above, point the --scrim-* overrides at\n" +
      "them (matching or beating their specificity), then update\n" +
      "SCRIM_VENDOR_FINGERPRINT in scripts/build.js."
    );
  }
  console.log(`Scrim guard OK — vendor fingerprint ${fp}, ${found.length} vendor dim rule(s) overridden`);
}

