#!/usr/bin/env node
/**
 * Pre-render gallery + testimonials into the HTML files so AI/search crawlers
 * (which don't run JS) can index the content. Without this, the gallery and
 * testimonials sections look like empty <div>s in the page source.
 *
 * Inputs:  data/gallery.csv, data/testimonials.yaml
 * Outputs: rewrites regions between `<!-- BUILD:name -->` and `<!-- /BUILD:name -->`
 *          marker pairs in explore.html, explore/gallery.html, explore/testimonials.html.
 *
 * Run:     node scripts/build.js
 *
 * Gallery schema (CSV columns):
 *   src         - path to image, MUST start with "/" so the JS path-rewrite works
 *   alt         - alt text for screen readers + SEO
 *   location    - bold title in the caption
 *   date        - YYYY | YYYY-MM | YYYY-MM-DD | empty (Unlabeled)
 *   description - caption subtitle
 *
 * Testimonials schema: see data/testimonials.yaml header.
 */
const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");
const { imageSize } = require("image-size");
const { spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");

// --- sibling helpers ----------------------------------------------------
// A "Cannot find module" here is nearly always an UNTRACKED helper, not a broken
// `npm install`: a file no clean checkout ever had and no blob, reflog or stash can
// restore. Two verbs, because the losses differ: need() is what GENERATION cannot run
// without; want() is a checker, and losing a checker must not also cost the site its
// build — so the site still ships, and every run says it shipped unchecked.
const missingGuards = [];
function need(mod) {
  try { return require(mod); } catch (e) {
    if (e.code !== "MODULE_NOT_FOUND") throw e;
    console.error(`\n${String(e.message).split("\n")[0]}\n\n` +
      `scripts/build.js cannot generate anything without ${mod}. Copy it back from a\n` +
      `machine that still has it, then \`git add scripts/\` so the next clone has it too.\n`);
    process.exit(1);
  }
}
function want(mod, fn) {
  let g;
  // Only a missing THIS module is tolerated; a guard that loads and then fails
  // is a real finding and must keep failing the build.
  try { g = require(mod); } catch (e) {
    if (e.code !== "MODULE_NOT_FOUND" || !String(e.message).includes(mod)) throw e;
    missingGuards.push(mod);
    return;
  }
  g[fn]();
}

// The same hazard one step earlier: the file is HERE but git does not know about it, so
// the next clean checkout is the one that breaks. Asked of git rather than of a filename
// list, so a helper added tomorrow is covered by itself, and scoped to the two tooling
// directories — a missing data file names itself in an ENOENT, a missing module does not.
// Silent without git: a tarball export has no repo and so no risk. This is the reminder;
// .githooks/pre-commit is the stop, and both ask git the same question.
function warnUntrackedBuildDeps() {
  const ls = spawnSync("git", ["ls-files", "--others", "--exclude-standard", "--", "scripts", ".githooks"],
    { cwd: ROOT, encoding: "utf8" });
  if (ls.error || ls.status !== 0) return;
  const untracked = (ls.stdout || "").split("\n").map((x) => x.trim()).filter(Boolean).sort();
  if (!untracked.length) return;
  console.warn(
    `\n!!  UNTRACKED BUILD DEPENDENC${untracked.length > 1 ? "IES" : "Y"} — never committed, so a fresh clone,\n` +
    `    \`git clean -fd\` or \`git worktree add\` loses ${untracked.length > 1 ? "them" : "it"} for good: no blob, no reflog,\n` +
    `    no stash. Commits are blocked until:  git add ${untracked.join(" ")}\n`
  );
}

